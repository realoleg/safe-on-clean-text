from __future__ import annotations

from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from safe_on_clean_text.paper import FIGURES, PAPER_DIR, TABLES, display_number
from safe_on_clean_text.paper.tables import WORST_DOMAIN_SCENARIO
from safe_on_clean_text.study import ALPHA, DREADDIT_MODELS, SDCNL_MODELS


def results_digest(dreaddit: dict, sdcnl: dict) -> None:
    """
    results/paper/results_digest.md: every number the paper cites, grouped by section, each with its source file; read
    back from the tables written above (primary aggregation; medians with 2.5-97.5% over resplits).
    """

    def number(value: Any) -> str:
        if isinstance(value, (bool, np.bool_)) or not isinstance(value, (int, float, np.number)):
            return str(value)
        return "" if np.isnan(value) else display_number(value)

    def interval(row: pd.Series) -> str:
        return f"{number(row['median'])} [{number(row['q025'])}, {number(row['q975'])}]"

    lines = [
        "# Results digest",
        "",
        "Every number the paper cites, with its source file (under the repository root). Generated by "
        "`safe-on-clean-text paper`; do not edit by hand. Conformal numbers: alpha = 0.10, primary aggregation (per resplit "
        "averaged over an encoder's seeds, then median [2.5%, 97.5%] over 1,000 resplits).",
        "",
    ]

    def section(title: str, rows: list[tuple[str, str, str]]) -> None:
        lines.extend([f"## {title}", "", "| quantity | value | source |", "| --- | --- | --- |"])
        lines.extend(f"| {q} | {v} | `{src}` |" for q, v, src in rows)
        lines.append("")

    # Data
    source = str(TABLES / "table1_data.csv")
    data = pd.read_csv(source)
    data = data[data["quantity"].isin(["rows", "posts", "author groups", "risk share", "median words"])]
    section("Data", [(f"{r.dataset} {r.split}: {r.quantity}", number(r.value), source) for r in data.itertuples()])

    # Classification (fixed test split, clean, raw probabilities)
    source = str(TABLES / "table2_classification.csv")
    table = pd.read_csv(source)
    table = table[
        (table["split"] == "test")
        & (table["probabilities"].isin(["raw"]))
        & (
            table["model"].isin(DREADDIT_MODELS) & (table["dataset"] == "dreaddit")
            | table["model"].isin(SDCNL_MODELS) & (table["dataset"] == "sdcnl")
        )
    ]
    rows = []
    for r in table.itertuples():
        for metric in ["macro_f1", "auroc", "ece_width15"]:
            spread = (
                ""
                if r.n_seeds < 2
                else f" (seeds {number(getattr(r, metric + '_min'))}–{number(getattr(r, metric + '_max'))})"
            )
            rows.append(
                (
                    f"{r.dataset} {r.model}: test {metric} ({'median over seeds' if r.n_seeds > 1 else 'single run'})",
                    number(getattr(r, metric + "_median")) + spread,
                    source,
                )
            )
    section("Classification (fixed test split, clean)", rows)

    # Headline conformal numbers per model
    rows = []
    for dataset, name, models in [
        ("dreaddit", "table3_conformal.csv", DREADDIT_MODELS),
        ("sdcnl", "table5_sdcnl.csv", SDCNL_MODELS),
    ]:
        source = str(TABLES / name)
        table = pd.read_csv(source)
        table = table[table["alpha"] == ALPHA]
        for model in models:
            for scenario, method, metric in [
                ("clean", "M0", "coverage"),
                ("clean", "M0", "c0"),
                ("clean", "M0", "c1"),
                ("clean", "M1", "c1"),
                ("pi=0.1", "M0", "coverage_pi=0.1"),
                ("pi=0.1", "M1", "coverage_pi=0.1"),
                ("clean", "M0", "workload_per_1000_pi=0.1"),
                ("clean", "M1", "workload_per_1000_pi=0.1"),
                ("head_25", "M0", "c1"),
                ("head_25", "M1", "c1"),
                ("head_25", "M3", "c1"),
                ("head_25", "M3-mix", "c1"),
                ("head_25", "M1", "workload_per_1000_pi=0.1"),
                ("head_25", "M3", "workload_per_1000_pi=0.1"),
                (WORST_DOMAIN_SCENARIO, "M0", "coverage"),
            ]:
                part = table[
                    (table["model"] == model)
                    & (table["scenario"] == scenario)
                    & (table["method"] == method)
                    & (table["metric"] == metric)
                ]
                if not part.empty:
                    rows.append((f"{dataset} {model}: {scenario} {method} {metric}", interval(part.iloc[0]), source))
    section("Headline conformal numbers (Dreaddit Table 3, SDCNL Table 5)", rows)

    # Hypotheses
    source = str(TABLES / "table6_hypotheses.csv")
    table = pd.read_csv(source)
    lines.extend(
        [
            "## Hypotheses (criteria and verdicts, primary aggregation)",
            "",
            "| hypothesis | scope | quantity | criterion | value | margin | meets | source |",
            "| --- | --- | --- | --- | --- | --- | --- | --- |",
        ]
    )
    for r in table.itertuples():
        value = r.value
        try:
            value = number(float(value))
        except ValueError:
            pass
        lines.append(
            f"| {r.hypothesis} | {r.scope} | {r.quantity} | {number(r.criterion)} | {value} | {number(r.margin)} | {number(r.meets)} | `{source}` |"
        )
    lines.append("")

    source = str(TABLES / "appendix_table6_sensitivity_pooled.csv")
    table = pd.read_csv(source)
    section(
        "Sensitivity: outcomes that differ under the pooled seed x resplit aggregation",
        [
            (
                f"{r.hypothesis} {r.scope}: {r.quantity}",
                f"primary {r.value_primary} vs pooled {r.value_sensitivity_pooled}",
                source,
            )
            for r in table.itertuples()
        ],
    )

    # Key mechanism numbers (Dreaddit, DistilBERT unless stated)
    rows = []
    source = str(FIGURES / "figure_mechanism_thresholds.csv")
    table = pd.read_csv(source)
    for r in table[table["model"] == "distilbert"].itertuples():
        rows.append(
            (
                f"distilbert {r.method} ({r.length_bucket}): stress in the set if p(stress) >=",
                interval(pd.Series(r._asdict())),
                source,
            )
        )
    source = str(TABLES / "appendix_unanimous.csv")
    table = pd.read_csv(source)
    for subset in ["all_rows", "unanimous"]:
        for method in ["M0", "M1", "M3-mix"]:
            part = table[
                (table["model"] == "distilbert")
                & (table["subset"] == subset)
                & (table["condition"] == "head_25")
                & (table["method"] == method)
                & (table["metric"] == "c1")
            ]
            rows.append((f"distilbert head_25 {method} c1, {subset}", interval(part.iloc[0]), source))
    source = str(TABLES / "appendix_agreement_auroc.csv")
    table = pd.read_csv(source)
    for r in table[table["model"] == "distilbert"].itertuples():
        rows.append(
            (
                f"distilbert AUROC {r.score} ({r.method}) -> non-unanimous label",
                interval(pd.Series(r._asdict())),
                source,
            )
        )
    source = str(TABLES / "appendix_confident_miss_liwc.csv")
    table = pd.read_csv(source)
    for r in table[(table["model"] == "distilbert") & (table["method"] == "M0")].itertuples():
        rows.append(
            (f"distilbert confident misses vs caught (M0): {r.metric}", interval(pd.Series(r._asdict())), source)
        )
    source = str(FIGURES / "figure3_prevalence.csv")
    table = pd.read_csv(source)
    for r in table[(table["model"] == "distilbert") & (table["prevalence"].isin([0.05, 0.1]))].itertuples():
        rows.append(
            (f"distilbert {r.scenario} at pi = {r.prevalence}: {r.metric}", interval(pd.Series(r._asdict())), source)
        )
    source = str(TABLES / "appendix_lodo.csv")
    table = pd.read_csv(source)
    for r in table[
        (table["model"] == "distilbert") & (table["alpha"] == ALPHA) & (table["metric"] == "coverage")
    ].itertuples():
        rows.append(
            (
                f"distilbert LODO {r.domain} {r.method} coverage (band [{number(r.band_low)}, {number(r.band_high)}])",
                interval(pd.Series(r._asdict())),
                source,
            )
        )
    section("Key mechanism numbers", rows)

    # Validation checks of the conformal layer (results/checks)
    checks_dir = Path(dreaddit["paths"]["checks_dir"])
    rows = []
    source = str(checks_dir / "conformal_checks.csv")
    conformal = pd.read_csv(source)
    for r in conformal[conformal["key"].str.endswith("share_in_band")].itertuples():
        rows.append((f"synthetic exchangeable data, {r.section}: {r.key}", number(float(r.value)), source))
    for key in ["max_abs_difference"]:
        for r in conformal[conformal["key"] == key].itertuples():
            rows.append(
                (f"{r.section}: analytic vs bootstrap prevalence reweighting, {key}", number(float(r.value)), source)
            )
    for key in ["set_rows_compared", "set_rows_changed"]:
        value = conformal[(conformal["section"] == "log_odds_equivalence") & (conformal["key"] == key)]["value"].iloc[0]
        rows.append((f"log-odds vs 1 - p scores (synthetic): {key}", value, source))
    source = str(checks_dir / "temperature_invariance.csv")
    invariance = pd.read_csv(source)
    invariance = invariance[invariance["section"] == "t_invariance"]
    for key in ["set_rows_compared", "set_rows_changed"]:
        values = invariance[invariance["key"] == key]["value"].astype(float)
        rows.append((f"temperature scaling, all {len(values)} runs: {key} (sum)", str(int(values.sum())), source))
    source = str(checks_dir / "prevalence_bootstrap.csv")
    bootstrap = pd.read_csv(source)
    rows.append(
        (
            "prevalence reweighting vs stratified bootstrap: comparisons within tolerance",
            f"{int(bootstrap['ok'].sum())} of {len(bootstrap)}",
            source,
        )
    )
    rows.append(
        (
            "prevalence reweighting vs stratified bootstrap: max absolute difference",
            number(float(bootstrap["abs_difference"].max())),
            source,
        )
    )
    section("Validation checks", rows)

    # Exploratory (post hoc)
    rows = []
    source = str(TABLES / "exploratory_slack_spearman.csv")
    for r in pd.read_csv(source).itertuples():
        rows.append(
            (
                f"EXPLORATORY: Spearman slack vs head_25 c1(M1) - c1(M0), {r.scope} (n = {r.n_runs})",
                number(r.spearman_slack_vs_difference_median),
                source,
            )
        )
    source = str(TABLES / "exploratory_slack_points.csv")
    for r in pd.read_csv(source).itertuples():
        rows.append(
            (
                f"EXPLORATORY: {r.dataset} {r.model} seed {r.seed}: slack / head_25 M1 - M0",
                f"{number(r.slack)} / {number(r.difference_median)} [{number(r.difference_q025)}, {number(r.difference_q975)}]",
                source,
            )
        )
    source = str(Path(sdcnl["evaluation"]["output_dir"]) / "exploratory_addendum.csv")
    addendum = pd.read_csv(source)
    addendum = addendum[(addendum["section"] == "mechanism_by_dataset") & (addendum["model"] == "distilbert")]
    for r in addendum.itertuples():
        rows.append(
            (
                f"EXPLORATORY: {r.dataset} distilbert {r.condition}: median p(risk) of risk posts / share above M0 / M1 cutoff",
                f"{number(r.median_p_risk_posts)} / {number(r.share_risk_above_M0_cutoff)} / {number(r.share_risk_above_M1_cutoff)}",
                source,
            )
        )
    section("Exploratory results (post hoc, labelled as such in the paper)", rows)

    # Exploratory band decomposition of the M1 - M0 gap: band mass = c1(M0) - c1(M1)
    rows = []
    source = str(TABLES / "appendix_band_decomposition.csv")
    table = pd.read_csv(source)
    rows.append(
        (
            "EXPLORATORY: max absolute difference band mass vs c1(M0) - c1(M1), all runs, seeds, resplits and conditions",
            f"{table['identity_max_abs_difference'].max():.1e}",
            source,
        )
    )
    stats = table.set_index(["dataset", "model", "seed", "condition", "metric"]).sort_index()
    for dataset, model in table[["dataset", "model"]].drop_duplicates().itertuples(index=False):
        primary = stats.loc[(dataset, model, "seed-averaged")]
        rows.append(
            (
                f"EXPLORATORY: {dataset} {model}: p(risk) cut-off on clean, M0 / M1",
                f"{interval(primary.loc[('clean', 'M0_risk_in_set_if_p_at_least')])} / "
                f"{interval(primary.loc[('clean', 'M1_risk_in_set_if_p_at_least')])}",
                source,
            )
        )
        rows.append(
            (
                f"EXPLORATORY: {dataset} {model} clean: band mass",
                interval(primary.loc[("clean", "band_mass")]),
                source,
            )
        )
        for condition in ["head_25", "tail_25"]:
            band = primary.loc[(condition, "band_mass")]
            rows.append(
                (
                    f"EXPLORATORY: {dataset} {model} {condition}: band mass / change vs clean / ratio of medians",
                    f"{interval(band)} / {interval(primary.loc[(condition, 'band_mass_change_vs_clean')])} / "
                    f"{number(band['ratio_of_medians']) or 'empty'}",
                    source,
                )
            )
        for seed in table[(table["dataset"] == dataset) & (table["model"] == model)]["seed"].unique():
            if seed != "seed-averaged":
                per_seed = stats.loc[(dataset, model, seed)]
                rows.append(
                    (
                        f"EXPLORATORY: {dataset} {model} seed {seed}: band mass clean / head_25",
                        f"{interval(per_seed.loc[('clean', 'band_mass')])} / "
                        f"{interval(per_seed.loc[('head_25', 'band_mass')])}",
                        source,
                    )
                )
    section("Exploratory: band decomposition of the M1 - M0 risk-class coverage gap (post hoc)", rows)

    (PAPER_DIR / "results_digest.md").write_text("\n".join(lines), encoding="utf-8")
